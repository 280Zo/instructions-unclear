#!/usr/bin/env python3
"""Turn a *service fragment* Ignition config into an idempotent bash script
that applies the same users, folders, files, links and units to a running
FCOS VM. This is the "push live" half of the hybrid model: the VM gets
exactly what Ignition would give it on the next rebuild.

It fails closed. Anything outside the small subset service fragments use
(disks, filesystems, passwords, SSH keys, merges, remote URLs, paths outside
/etc, /var, /usr/local) raises UnsupportedIgnition, and no script is written.

Usage: ign_to_script.py <fragment.ign>... [--root DIR]   (one script on stdout)
Run on the VM as root:  sudo bash apply.sh
Set IGN_DRY_RUN=1 to skip privileged steps (used by the tests).
"""

import base64
import gzip
import json
import posixpath
import re
import shlex
import sys
import urllib.parse

ALLOWED_ROOTS = ("/etc/", "/var/", "/usr/local/")
NAME = re.compile(r"^[a-z_][a-z0-9_-]{0,31}$")
UNIT = re.compile(r"^[A-Za-z0-9@._-]+$")

HEADER = """#!/bin/bash
set -euo pipefail
# Generated by tools/ign_to_script.py. Do not edit; regenerate from the .ign.
priv() { if [[ -n "${IGN_DRY_RUN:-}" ]]; then echo "skip: $*"; else "$@"; fi; }
# Runs as root in folders a service user owns: never follow a symlink a
# container could have planted. A path must resolve to itself, except through
# FCOS's own layout links (/usr/local -> ../var/usrlocal, ...), and only when
# such a link points exactly there and belongs to the user running this.
FCOS_LINKS="/usr/local:../var/usrlocal /home:var/home /mnt:var/mnt /opt:var/opt /srv:var/srv /root:var/roothome"
safe() {
  local want=$1 pair link
  for pair in $FCOS_LINKS; do
    link="${IGN_ROOT:-}${pair%%:*}"
    # The link's own target must be a plain folder too (realpath equals the lexical target).
    if [[ ( "$1" == "$link" || "$1" == "$link"/* ) && -L "$link" && "$(readlink -- "$link")" == "${pair#*:}" \
          && "$(stat -c %u -- "$link")" == "$(id -u)" \
          && "$(realpath -m -- "$link")" == "$(realpath -m -s -- "$(dirname -- "$link")/${pair#*:}")" ]]; then
      want="$(realpath -m -- "$link")${1#"$link"}"
      break
    fi
  done
  if [[ "$(realpath -m -- "$1")" != "$want" ]]; then
    echo "STOP: $1 goes through a symlink; nothing more done" >&2
    exit 1
  fi
}
# Who writes: root (the runner) only where every existing folder on the way is
# the runner's and writable by nobody else. Inside a folder a service account
# owns, that account writes (setpriv), so a symlink it plants in the meantime
# can only reach what it could write anyway.
# IGN_TEST_RUNNER_UID is for the tests only: it makes the test user's folders
# count as a service's.
RUNNER_UID="${IGN_TEST_RUNNER_UID:-$(id -u)}"
writer() {
  local rel="${1#"${IGN_ROOT:-}"}" d="${IGN_ROOT:-}" part who="" owner perm
  local -a parts
  IFS=/ read -ra parts <<< "${rel#/}"
  for part in "${parts[@]:0:${#parts[@]}-1}"; do
    d="$d/$part"
    [[ -e "$d" ]] || break
    owner="$(stat -L -c '%u:%g' -- "$d")"
    perm="$(stat -L -c '%a' -- "$d")"
    # A folder others can write could be raced by them, whoever writes: stop.
    if (( 8#$perm & 8#022 )); then
      echo "STOP: $d is writable by others (mode $perm); nothing more done" >&2
      exit 1
    fi
    if [[ -z "$who" ]]; then
      if [[ "${owner%%:*}" != "$RUNNER_UID" ]]; then who="$owner"; fi
    elif [[ "${owner%%:*}" != "${who%%:*}" && "${owner%%:*}" != "$RUNNER_UID" ]]; then
      echo "STOP: $d belongs to another account inside a folder of $who; nothing more done" >&2
      exit 1
    fi
  done
  echo "$who"
}
# as <uid:gid or ''> <command...>: run as that account, or as the runner when empty.
as() {
  local who=$1; shift
  if [[ -z "$who" ]]; then "$@"
  elif [[ -n "${IGN_TEST_RUNNER_UID:-}" ]]; then echo "as $who: $*"; "$@"
  else setpriv --reuid="${who%%:*}" --regid="${who#*:}" --clear-groups -- "$@"; fi
}
# ids <owner>: "uid:gid" for a fragment owner given by number or name.
ids() {
  local u="${1%%:*}" g="${1#*:}"
  [[ "$1" == *:* ]] || g=""
  [[ "$u" =~ ^[0-9]+$ ]] || u="$(id -u -- "$u")"
  if [[ -n "$g" && ! "$g" =~ ^[0-9]+$ ]]; then g="$(getent group -- "$g" | cut -d: -f3)"; fi
  echo "$u:${g:-$u}"
}
# A service's folder holds only that service's files: a fragment owner that
# isn't the folder's account would need root to write there.
same_owner() {
  local who=$1 owner=$2 path=$3
  if [[ -n "$who" && -n "$owner" && "$(ids "$owner")" != "$who" ]]; then
    echo "STOP: $path is in a folder of $who but its fragment says owner $owner; nothing more done" >&2
    exit 1
  fi
}
# Ignition sets a folder's mode and owner only when it creates it; an app may
# have taken an existing folder over (a database's data folder), so leave it.
newdir() {
  local mode=$1 owner=$2 path=$3 who
  safe "$path"
  if [[ -d "$path" && ! -L "$path" ]]; then
    local is says
    is="$(stat -c '%a %u:%g' -- "$path")"
    says="$(printf '%o' "$((8#$mode))")${owner:+ $(ids "$owner")}"
    if [[ "$is" == "$says" || ( -z "$owner" && "${is%% *}" == "${says%% *}" ) ]]; then
      echo "kept: $path"
    else
      echo "kept: $path (is $is, fragment says $says)"
    fi
    return 0
  fi
  who="$(writer "$path")"
  same_owner "$who" "$owner" "$path"
  as "$who" install -d -m "$mode" "$path"
  if [[ -z "$who" && -n "$owner" ]]; then priv chown -h "$owner" "$path"; fi
}
# lnk <target> <path>: a symlink, made by the same writer as a file there.
lnk() {
  local target=$1 path=$2 who
  safe "$(dirname -- "$path")"
  who="$(writer "$path")"
  as "$who" mkdir -p "$(dirname -- "$path")"
  as "$who" ln -sfn -- "$target" "$path"
}
# put <mode> <owner or ''> <overwrite 0|1> <path> <base64 data>
# A file with no owner inside a service's folder is written by, and belongs to,
# that service (it owns the folder and could replace the file anyway).
# overwrite 0 is Ignition's default: an existing file must already match.
put() {
  local mode=$1 owner=$2 overwrite=$3 path=$4 data=$5 tmp who
  safe "$path"
  who="$(writer "$path")"
  same_owner "$who" "$owner" "$path"
  as "$who" mkdir -p "$(dirname "$path")"
  safe "$path"
  if [[ "$overwrite" == 0 && ( -e "$path" || -L "$path" ) ]]; then
    if printf %s "$data" | base64 -d | cmp -s - "$path"; then
      echo "unchanged: $path"
      return 0
    fi
    echo "STOP: $path exists and its fragment says overwrite: false (Ignition would fail too); nothing more done" >&2
    exit 1
  fi
  tmp=$(as "$who" mktemp "$path.XXXXXX")
  tmp="${tmp##*$'\n'}"
  printf %s "$data" | base64 -d | as "$who" tee -- "$tmp" >/dev/null
  as "$who" chmod "$mode" "$tmp"
  if [[ -z "$who" && -n "$owner" ]]; then priv chown "$owner" "$tmp"; fi
  as "$who" mv -f "$tmp" "$path"
}
"""


class UnsupportedIgnition(Exception):
    pass


def _check_keys(obj: dict, allowed: set, where: str) -> None:
    extra = set(obj) - allowed
    if extra:
        raise UnsupportedIgnition(f"{where}: unsupported field(s) {sorted(extra)}")


def _path(path: str) -> str:
    if not isinstance(path, str) or not path.startswith("/"):
        raise UnsupportedIgnition(f"path must be absolute: {path!r}")
    if ".." in path.split("/") or posixpath.normpath(path) != path:
        raise UnsupportedIgnition(f"path must be normalized: {path!r}")
    if not path.startswith(ALLOWED_ROOTS):
        raise UnsupportedIgnition(f"path outside {ALLOWED_ROOTS}: {path!r}")
    return path


def _name(value: str, pattern: re.Pattern, what: str) -> str:
    if not isinstance(value, str) or not pattern.fullmatch(value):  # fullmatch: "$" would let a final newline pass
        raise UnsupportedIgnition(f"invalid {what}: {value!r}")
    return value


def _mode(value, default: int) -> str:
    mode = default if value is None else value
    if not isinstance(mode, int) or not 0 <= mode <= 0o7777:
        raise UnsupportedIgnition(f"invalid mode: {value!r}")
    return f"{mode:04o}"


def _id(value, what: str) -> str:
    if type(value) is not int or value < 0:
        raise UnsupportedIgnition(f"invalid {what}: {value!r}")
    return str(value)


def _owner(entry: dict) -> str | None:
    parts = []
    for key in ("user", "group"):
        ref = entry.get(key) or {}
        _check_keys(ref, {"id", "name"}, key)
        if "id" in ref:
            parts.append(_id(ref["id"], f"{key} id"))
        elif "name" in ref:
            parts.append(_name(ref["name"], NAME, f"{key} name"))
        else:
            parts.append("")
    if not any(parts):
        return None
    return ":".join(parts).rstrip(":") if parts[1] == "" else ":".join(parts)


def _contents(contents: dict | None) -> bytes:
    if not contents:
        return b""
    _check_keys(contents, {"source", "compression", "verification"}, "contents")
    source = contents.get("source")
    if source is None:
        return b""
    if not source.startswith("data:"):
        raise UnsupportedIgnition("only data: URLs are allowed (no remote sources)")
    head, _, body = source.partition(",")
    try:
        raw = base64.b64decode(body, validate=True) if head.endswith(";base64") else urllib.parse.unquote_to_bytes(body)
    except ValueError:
        raise UnsupportedIgnition("a data: URL holds invalid base64") from None
    compression = contents.get("compression")
    if compression == "gzip":
        raw = gzip.decompress(raw)
    elif compression not in (None, ""):
        raise UnsupportedIgnition(f"unsupported compression {compression!r}")
    return raw


def _q(text: str) -> str:
    return shlex.quote(text)


def to_script(config: dict, root: str = "") -> str:
    _check_keys(config, {"ignition", "passwd", "storage", "systemd"}, "config")
    _check_keys(config.get("ignition", {}), {"version"}, "ignition")
    accounts = config.get("passwd", {})
    storage = config.get("storage", {})
    systemd = config.get("systemd", {})
    _check_keys(accounts, {"groups", "users"}, "passwd")
    _check_keys(storage, {"directories", "files", "links"}, "storage")
    _check_keys(systemd, {"units"}, "systemd")

    def at(path: str) -> str:
        return _q(root.rstrip("/") + _path(path)) if root else _q(_path(path))

    lines = [HEADER, f"IGN_ROOT={_q(root.rstrip('/')) if root else _q('')}"]

    for group in accounts.get("groups", []):
        _check_keys(group, {"name", "gid"}, "group")
        name = _name(group["name"], NAME, "group name")
        gid = f"-g {_id(group['gid'], 'gid')} " if "gid" in group else ""
        lines.append(f"getent group {name} >/dev/null || priv groupadd {gid}{name}")

    for user in accounts.get("users", []):
        _check_keys(user, {"name", "uid", "primaryGroup", "groups", "shell"}, "user")
        name = _name(user["name"], NAME, "user name")
        args = []
        if "uid" in user:
            args.append(f"-u {_id(user['uid'], 'uid')}")
        if user.get("primaryGroup"):
            args.append(f"-g {_name(user['primaryGroup'], NAME, 'group name')}")
        extra = [_name(g, NAME, "group name") for g in user.get("groups", [])]
        if extra:
            args.append(f"-G {','.join(extra)}")
        if user.get("shell"):
            args.append(f"-s {_q(user['shell'])}")
        args.append("-m")
        lines.append(f"id -u {name} >/dev/null 2>&1 || priv useradd {' '.join(args)} {name}")

    # Shallowest first, as Ignition does, so a declared parent is made (with its
    # owner) before a deeper folder would create it as root.
    for directory in sorted(storage.get("directories", []), key=lambda d: _path(d["path"]).rstrip("/").count("/")):
        _check_keys(directory, {"path", "mode", "user", "group", "overwrite"}, "directory")
        owner = _owner(directory) or ""
        lines.append(f"newdir {_mode(directory.get('mode'), 0o755)} {_q(owner)} {at(directory['path'])}")

    for entry in storage.get("files", []):
        _check_keys(entry, {"path", "mode", "contents", "user", "group", "overwrite"}, "file")
        if not isinstance(entry.get("overwrite", False), bool):
            raise UnsupportedIgnition("overwrite must be true or false")
        data = base64.b64encode(_contents(entry.get("contents"))).decode()
        owner = _owner(entry) or ""
        overwrite = 1 if entry.get("overwrite") else 0
        # The owner is set on the temp file before it is moved in place, so the
        # file is never briefly root-owned at its final path.
        lines.append(f"put {_mode(entry.get('mode'), 0o644)} {_q(owner)} {overwrite} {at(entry['path'])} '{data}'")

    for link in storage.get("links", []):
        _check_keys(link, {"path", "target", "hard", "user", "group", "overwrite"}, "link")
        if link.get("hard"):
            raise UnsupportedIgnition("hard links are not supported")
        target = _path(link["target"])
        lines.append(f"lnk {_q(target)} {at(link['path'])}")

    switches = []  # (enable|disable, unit); enabled left out means leave as is
    for unit in systemd.get("units", []):
        _check_keys(unit, {"name", "enabled", "contents", "dropins"}, "unit")
        name = _name(unit["name"], UNIT, "unit name")
        if unit.get("contents") is not None:
            data = base64.b64encode(unit["contents"].encode()).decode()
            lines.append(f"put 0644 '' 1 {at('/etc/systemd/system/' + name)} '{data}'")
        for dropin in unit.get("dropins", []):
            _check_keys(dropin, {"name", "contents"}, "dropin")
            dname = _name(dropin["name"], UNIT, "drop-in name")
            data = base64.b64encode((dropin.get("contents") or "").encode()).decode()
            lines.append(f"put 0644 '' 1 {at(f'/etc/systemd/system/{name}.d/{dname}')} '{data}'")
        if unit.get("enabled") is True:
            switches.append(("enable", name))
        elif unit.get("enabled") is False:
            switches.append(("disable", name))

    lines.append("priv systemctl daemon-reload")
    for action, name in switches:
        lines.append(f"priv systemctl {action} {name}")
    lines.append('echo "applied"')
    return "\n".join(lines) + "\n"


import zlib  # noqa: E402

# What a fragment of the wrong shape or with broken contents can raise; each is one error line, and no
# script is printed.
FRAGMENT_ERRORS = (UnsupportedIgnition, ValueError, KeyError, TypeError, AttributeError, OSError, EOFError,
                   zlib.error)


def _why(error: Exception) -> str:
    return str(error) if isinstance(error, UnsupportedIgnition) else \
        f"the fragment is not shaped as expected or its contents are broken ({type(error).__name__})"


def main(argv: list[str]) -> int:
    args = argv[1:]
    root = ""
    if "--root" in args:
        index = args.index("--root")
        if index + 1 >= len(args):
            print("ign_to_script: --root needs a directory", file=sys.stderr)
            return 2
        root = args[index + 1]
        del args[index:index + 2]
    if not args:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    # Convert every fragment before printing anything: one refused fragment
    # means no script at all, never a partial one.
    configs = []
    for path in args:
        try:
            with open(path, encoding="utf-8") as handle:
                configs.append((path, json.load(handle)))
        except (OSError, ValueError) as error:
            print(f"ign_to_script: {path}: {error}", file=sys.stderr)
            return 1
    # Every fragment's declared folders first (shallowest first, as Ignition merges
    # and sorts them), so an earlier fragment's file can't pre-create one as root.
    # Accounts of all fragments go first too: a folder may be owned by name.
    folders, groups, users = [], [], []
    for _path_name, config in configs:
        storage = config.get("storage") if isinstance(config, dict) else None
        if isinstance(storage, dict):
            folders += storage.get("directories", [])
        accounts = config.get("passwd") if isinstance(config, dict) else None
        if isinstance(accounts, dict):
            groups += accounts.get("groups", [])
            users += accounts.get("users", [])
    bodies = []
    try:
        # The same folder in several fragments: the last one wins, as Ignition merges.
        last = {}
        for folder in folders:
            if not isinstance(folder, dict):
                raise UnsupportedIgnition(f"a folder entry must be a mapping: {folder!r}")
            last.pop(folder.get("path"), None)
            last[folder.get("path")] = folder
        folders = list(last.values())
        if folders or groups or users:
            bodies.append("# --- accounts and declared folders of all fragments ---\n"
                          + to_script({"passwd": {"groups": groups, "users": users},
                                       "storage": {"directories": folders}}, root=root)[len(HEADER):])
        for path, config in configs:
            try:
                rest = json.loads(json.dumps(config))
                if isinstance(rest, dict):
                    rest.pop("passwd", None)
                    if isinstance(rest.get("storage"), dict):
                        rest["storage"].pop("directories", None)
                script = to_script(rest, root=root)
            except FRAGMENT_ERRORS as error:
                print(f"ign_to_script: {path}: {_why(error)}", file=sys.stderr)
                return 1
            bodies.append(f"# --- {path} ---\n" + script[len(HEADER):])
    except FRAGMENT_ERRORS as error:
        print(f"ign_to_script: declared folders: {_why(error)}", file=sys.stderr)
        return 1
    sys.stdout.write(HEADER + "\n".join(bodies))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
