def agent_path(name):
    return f"agents/{name}/subagents/{name}.md"


def agent_specs():
    """Agent name -> spec, for every agent this script writes rules for."""
    specs = {name: {"mode": "deny-specialists"} for name in OVERRIDES}
    specs.update(SPECIALISTS)
    specs.update({Path(path).stem: spec for path, spec in MARKED.items()})
    return specs


def allowed_skills(spec, installed):
    """Skill IDs the agent may load, given the repo skills installed with it."""
    if spec.get("mode") == "deny-specialists":
        specialist = {s for b in SPECIALIST_BUNDLES for s in BUNDLES[b]}
        return (set(installed) | set(SHARED)) - specialist
    return set(SHARED).union(*(BUNDLES[b] for b in spec["bundles"]))


def allowed_mcp(spec):
    if spec.get("mode") == "deny-specialists":
        return [m for m in MCP if m not in BUILD_MCP_DENY]
    return spec["mcp"]


def rule(action, resource, effect):
    return f'- {{action: "{action}", resource: "{resource}", effect: {effect}}}'


def rules_for(spec):
    if spec.get("mode") == "deny-specialists":
        denied = sorted({s for b in SPECIALIST_BUNDLES for s in BUNDLES[b]})
        lines = [rule("skill", s, "deny") for s in denied]
        lines += [rule(MCP[m], "*", "deny") for m in BUILD_MCP_DENY]
        return lines
    lines = [rule("skill", "*", "deny")]
    lines += [rule("skill", s, "allow") for s in sorted(allowed_skills(spec, []))]
    lines += [rule(MCP[m], "*", "deny") for m in MCP if m not in spec["mcp"]]
    if spec["subagents"] is not None:
        lines += [rule("subagent", "*", "deny")]
        lines += [rule("subagent", a, "allow") for a in spec["subagents"]]
    return lines


def block(lines, indent="    "):
    return "\n".join([indent + BEGIN] + [indent + l for l in lines] + [indent + END])


def yaml_string(value):
    return json.dumps(value, ensure_ascii=False)


def specialist(name, spec):
    """One file for every tool. In OpenCode the body replaces the base prompt."""
    denied = [f"mcp__{m}" for m in MCP if m not in spec["mcp"]]
    lines = [f"name: {name}", 'targets: ["*"]', f"description: {yaml_string(spec['description'])}",
             "opencode:", "  mode: all", "  permissions:", block(rules_for(spec)),
             "claudecode:", "  disallowedTools:"] + [f"    - {d}" for d in denied]
    return "---\n" + "\n".join(lines) + "\n---\n\n" + agent_body(spec) + "\n"


def agent_body(spec):
    return spec["instructions"] + "\n\n" + BASE_INSTRUCTIONS


def override(name, mode):
    return (f"---\nname: {name}\ntargets: [\"opencode\"]\nopencode:\n  mode: {mode}\n"
            f"  permissions:\n{block(rules_for({'mode': 'deny-specialists'}))}\n---\n")


def marked(text, lines):
    match = re.search(rf"^( *){re.escape(BEGIN)}\n.*?^ *{re.escape(END)}$", text, re.M | re.S)
    if not match:
        raise ValueError("generated permission markers not found")
    return text[: match.start()] + block(lines, match[1]) + text[match.end():]


