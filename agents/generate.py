def map_data():
    installed = default_skills()
    listed = set(SHARED).union(*BUNDLES.values())
    groups = [("Superpowers", SUPERPOWERS), ("Tools and web research", TOOLS),
              ("Started by you with /, never shown to the model", USER_INVOKED)]
    for key, members in BUNDLES.items():
        title = BUNDLE_TITLES[key]
        absent = [s for s in members if s not in installed]
        if absent:
            title += f"; {', '.join(absent)} installs with its folder group, not default"
        groups.append((title, [s for s in members if s in installed]))
    groups.append(("Everything else in the default install", sorted(installed - listed)))

    def users(skills):
        result = []
        for agent in MAP_AGENTS:
            if agent == "explore":
                continue  # OpenCode's explore denies skills and MCP tools.
            if set(skills) <= allowed_skills(spec_of(agent), installed):
                result.append(agent)
        return result

    skills = [{"title": f"{t} ({len(s)})", "items": s, "agents": users(s)} for t, s in groups if s]
    mcp = [{"title": m, "items": [m], "agents": [a for a in MAP_AGENTS if a != "explore"
                                                 and m in allowed_mcp(spec_of(a))]} for m in MCP]

    def can_delegate(agent, target):
        if agent in ("general", "explore") or agent == target:
            return False  # OpenCode's general and explore can't launch subagents.
        spec = spec_of(agent)
        if spec.get("mode") == "deny-specialists" or spec.get("subagents") is None:
            return True
        return target in spec["subagents"]

    subagents = [{"title": t, "items": [t], "agents": [a for a in MAP_AGENTS if can_delegate(a, t)]}
                 for t in SUBAGENT_TARGETS + list(SPECIALISTS)]
    return {"agents": MAP_AGENTS, "skills": skills, "mcp": mcp, "subagents": subagents}


