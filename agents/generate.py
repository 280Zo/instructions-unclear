def page():
    data = json.dumps(map_data(), indent=1).replace("</", "<\\/")
    return HEADER + "\n" + PAGE.replace("__SCRIPT__", html.escape(SCRIPT)).replace("__DATA__", data)


def readme(text):
    pattern = rf"{re.escape(MAP_BEGIN)}.*?{re.escape(MAP_END)}"
    if not re.search(pattern, text, re.S):
        raise ValueError("README agent map markers not found")
    return re.sub(pattern, lambda _: readme_block(), text, flags=re.S)


def outputs():
    files = {}
    for name, spec in SPECIALISTS.items():
        files[agent_path(name)] = specialist(name, spec)
    for name, mode in OVERRIDES.items():
        files[agent_path(name)] = override(name, mode)
    for path, spec in MARKED.items():
        files[path] = marked((ROOT / path).read_text(), rules_for(spec))
    files["README.md"] = readme((ROOT / "README.md").read_text())
    files["docs/agents-map.html"] = page()
    files.update(hero_svgs())
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="Report drift without writing")
    args = parser.parse_args()
    stale = []
    for relative, content in outputs().items():
        path = ROOT / relative
        if not path.is_file() or path.read_text() != content:
            stale.append(relative)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if args.check and stale:
        print(f"Out of date; run {SCRIPT}:", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
