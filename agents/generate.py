def read_jsonc(path):
    text = re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*',
                  lambda m: "" if m[0].startswith("//") else m[0], Path(path).read_text())
    return json.loads(text)


def skill_ids(*roots):
    ids = set()
    for root in roots:
        ids.update(p.parent.name for p in (ROOT / root / "skills").glob("*/SKILL.md"))
    if not ids:
        raise SystemExit(f"No skills found under {roots}")
    return sorted(ids)


